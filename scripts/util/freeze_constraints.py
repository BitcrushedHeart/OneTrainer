"""Regenerate requirements-constraints.txt from the current venv.

requirements-global.txt references the constraints file with "-c", so every
install path (install.sh/update.sh on cloud pods, update.bat locally) resolves
transitive dependencies to the versions in this venv instead of whatever is
newest on PyPI. Without it, update.sh's "--upgrade-strategy eager" drifts every
unpinned transitive dependency on each pod.

Left out on purpose:
- editable git installs (diffusers, mgds, muon), pinned by commit in requirements-global.txt
- platform-specific packages (torch, onnxruntime, triton, nvidia, bitsandbytes), pinned per
  platform in requirements-cuda/rocm/default.txt; a cu130 pin here would break rocm/cpu installs
- yt-dlp, intentionally kept unpinned for site compatibility

Usage: venv/Scripts/python.exe scripts/util/freeze_constraints.py
"""

import re
import subprocess
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[2] / "requirements-constraints.txt"

EXCLUDE = re.compile(r"^(torch|torchvision|torchaudio|onnxruntime.*|triton.*|nvidia-(?!ml-py$).*|bitsandbytes|yt-dlp)$")


def main() -> int:
    freeze = subprocess.run(
        [sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout

    pins = []
    for line in freeze.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        # local wheel installs ("name @ file:///...") have no index version to pin to
        if " @ " in line:
            name = line.split(" @ ", 1)[0]
            print(f"warning: {name} is installed from a direct URL, pin it in requirements-global.txt", file=sys.stderr)
            continue
        name, _, version = line.partition("==")
        normalized = re.sub(r"[-_.]+", "-", name).lower()
        if EXCLUDE.match(normalized):
            continue
        pins.append((normalized, f"{name}=={version}"))

    header = (
        "# Generated by scripts/util/freeze_constraints.py from the local venv; do not edit by hand.\n"
        "# Locks transitive dependencies so cloud pods resolve the same versions as the local tree.\n"
    )
    OUTPUT.write_text(header + "".join(f"{pin}\n" for _, pin in sorted(pins)), encoding="utf-8", newline="\n")
    print(f"wrote {len(pins)} constraints to {OUTPUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
